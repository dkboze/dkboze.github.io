"""Pull Dan's posts from the Understanding AI feed into uai-posts.js.

The feed only holds the newest 20 posts across all writers, so posts are
accumulated here and never dropped. Existing entries are left untouched, so a
hand-edited title or description survives later runs.
"""
import html
import json
import pathlib
import re
import urllib.request
import xml.etree.ElementTree as ET
from email.utils import parsedate_to_datetime

FEED = "https://www.understandingai.org/feed"
AUTHOR = "Dan Kagan-Kans"
OUT = pathlib.Path(__file__).resolve().parent.parent / "uai-posts.js"
PREFIX = "// Generated by scripts/update_uai.py. Hand edits to existing entries are kept.\nwindow.UAI_POSTS = "

SMALL = set("a an and as at but by for from in into nor of on or per the to vs via with".split())


def title_case(s):
    words = s.split(" ")
    out = []
    for i, w in enumerate(words):
        m = re.search(r"[A-Za-z]", w)
        if not m:
            out.append(w)
            continue
        core = w[m.start():]
        first_or_last = i == 0 or i == len(words) - 1 or (i > 0 and words[i - 1].endswith(":"))
        if any(c.isupper() for c in core[1:]):  # OpenAI, AGI: leave alone
            out.append(w)
        elif core.lower() in SMALL and not first_or_last:
            out.append(w.lower())
        else:
            out.append(w[:m.start()] + "-".join(p[:1].upper() + p[1:] for p in core.split("-")))
    return " ".join(out)


def load():
    if not OUT.exists():
        return []
    return json.loads(OUT.read_text(encoding="utf-8")[len(PREFIX):].rstrip().rstrip(";"))


def main():
    req = urllib.request.Request(FEED, headers={"User-Agent": "kagankans.com feed updater"})
    root = ET.fromstring(urllib.request.urlopen(req, timeout=30).read())
    ns = {"dc": "http://purl.org/dc/elements/1.1/"}
    posts = load()
    known = {p["url"] for p in posts}
    for item in root.findall("./channel/item"):
        if item.findtext("dc:creator", namespaces=ns) != AUTHOR:
            continue
        url = item.findtext("link").split("?")[0]
        if url in known:
            continue
        posts.append({
            "title": title_case(html.unescape(item.findtext("title")).strip()),
            "desc": html.unescape(item.findtext("description") or "").strip(),
            "date": parsedate_to_datetime(item.findtext("pubDate")).date().isoformat(),
            "url": url,
        })
    posts.sort(key=lambda p: p["date"], reverse=True)
    OUT.write_text(PREFIX + json.dumps(posts, indent=2, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"{len(posts)} posts, {len(posts) - len(known)} new")


if __name__ == "__main__":
    main()
